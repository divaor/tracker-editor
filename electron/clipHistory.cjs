// Clipboard history (desktop, opt-in): the list of texts copied anywhere on
// the computer, newest first. Pinned entries stay; the rest are capped. Text
// that password managers mark as concealed is never kept.
const crypto = require('node:crypto');

const MAX_TEXT = 200_000; // longer copies are not kept
const DEFAULT_MAX = 50;

// Clipboard formats that ask history tools to skip the content: Windows,
// macOS (nspasteboard.org) and KDE. (Windows' CanIncludeInClipboardHistory
// depends on its value; main.cjs reads it.)
const CONCEALED_FORMATS = [
  'ExcludeClipboardContentFromMonitorProcessing',
  'Clipboard Viewer Ignore',
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType',
  'x-kde-passwordManagerHint',
];

// Electron lists the system's own formats as `electron application/osclipboard;format="<name>"`.
const formatName = (type) => /;format="([^"]+)"$/.exec(type)?.[1] ?? type;

/** Whether the clipboard's formats (as `clipboard.read()` lists them) say its content must not be kept. */
const isConcealed = (types = []) => types.map(formatName).some((f) => CONCEALED_FORMATS.includes(f));

/**
 * The list after copying `text`: it moves to the top (once), the oldest
 * unpinned entries go past `max`. Blank and very long texts are skipped.
 */
function addClip(list, text, { max = DEFAULT_MAX, now = Date.now(), id = crypto.randomUUID() } = {}) {
  if (typeof text !== 'string' || !text.trim() || text.length > MAX_TEXT) return list;
  const existing = list.find((e) => e.text === text);
  if (existing && list[0] === existing) return list;
  const entry = existing ? { ...existing, at: now } : { id, text, at: now, pinned: false };
  const rest = list.filter((e) => e !== existing);
  let unpinned = 0;
  return [entry, ...rest].filter((e) => e.pinned || ++unpinned <= max);
}

const removeClip = (list, id) => list.filter((e) => e.id !== id);
const pinClip = (list, id, pinned) => list.map((e) => (e.id === id ? { ...e, pinned: Boolean(pinned) } : e));
/** Clearing keeps the pinned entries. */
const clearClips = (list) => list.filter((e) => e.pinned);

module.exports = { addClip, removeClip, pinClip, clearClips, isConcealed, formatName, CONCEALED_FORMATS, MAX_TEXT, DEFAULT_MAX };
